const border = {
  top: { style: 'thin', color: { argb: BORDER_COLOR } },
  left: { style: 'thin', color: { argb: BORDER_COLOR } },
  bottom: { style: 'thin', color: { argb: BORDER_COLOR } },
  right: { style: 'thin', color: { argb: BORDER_COLOR } },
};

const columnWidth = (header) => {
  if (['Name', 'Description'].includes(header)) return header === 'Name' ? 44 : 60;
  if (['Short Description', 'Category', 'Tags', 'Packing'].includes(header)) return 34;
  if (['Brand', 'Hindi Name'].includes(header)) return 22;
  return Math.max(12, header.length + 4);
};

async function createCatalogWorkbookBuffer({ rows = EXAMPLE_ROWS, includeNotes = true } = {}) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = `${BRAND.name} Backend`;
  workbook.created = new Date();

  const sheet = workbook.addWorksheet('Products', { views: [{ state: 'frozen', ySplit: 1 }] });
  sheet.columns = TEMPLATE_HEADERS.map((header) => ({ header, key: header, width: columnWidth(header) }));
  const headerRow = sheet.getRow(1);
  headerRow.height = 22;
  headerRow.eachCell((cell) => {
    const required = REQUIRED_FOR_NEW.has(cell.value);
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: required ? REQUIRED_FILL : HEADER_FILL } };
    cell.alignment = { vertical: 'middle', horizontal: 'left' };
    cell.border = border;
  });

  rows.forEach((row) => sheet.addRow(TEMPLATE_HEADERS.map((header) => row[header] ?? null)));

  // SKU stays text (no lost leading zeros); money columns show two decimals.
  const columnIndex = (header) => TEMPLATE_HEADERS.indexOf(header) + 1;
  sheet.getColumn(columnIndex('SKU')).numFmt = '@';
  ['MRP', 'Retail Price', 'Wholesale Price'].forEach((header) => { sheet.getColumn(columnIndex(header)).numFmt = '#,##0.00'; });
  sheet.eachRow((row, rowNumber) => {
    if (rowNumber === 1) return;
    row.eachCell({ includeEmpty: true }, (cell) => {
      cell.border = border;
      cell.alignment = { vertical: 'top', wrapText: true };
    });
  });

  // Drop-down lists for the fixed-choice columns.
  const lists = {
    Status: '"active,draft,archived"',
    Negotiation: '"Yes,No"',
    Featured: '"Yes,No"',
    Hot: '"Yes,No"',
    'Pack Type': '"Packet,Coil,Bundle"',
  };
  for (const [header, formula] of Object.entries(lists)) {
    const column = columnIndex(header);
    for (let rowNumber = 2; rowNumber <= MAX_VALIDATED_ROWS; rowNumber += 1) {
      sheet.getCell(rowNumber, column).dataValidation = {
        type: 'list',
        allowBlank: true,
        formulae: [formula],
        showErrorMessage: false,
      };
    }
  }

  if (includeNotes) {
    const notes = workbook.addWorksheet('Notes');
    notes.columns = [{ width: 24 }, { width: 18 }, { width: 110 }];
    const addHeading = (text) => {
      const row = notes.addRow([text]);
      row.font = { bold: true, size: 13, color: { argb: HEADER_FILL } };
    };
    const addLines = (lines) => {
      lines.forEach(([first]) => {
        if (first === null) { notes.addRow([]); return; }
        const row = notes.addRow([first]);
        row.alignment = { wrapText: false };
      });
    };

    const [introHeading, ...intro] = NOTES;
    addHeading(introHeading[0]);
    addLines(intro);

    addHeading('Columns');
    const columnsHeader = notes.addRow(['Column', 'Needed', 'What to enter']);
    columnsHeader.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    columnsHeader.eachCell((cell) => { cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } }; });
    for (const header of TEMPLATE_HEADERS) {
      const [needed, text] = COLUMN_NOTES[header] || ['No', ''];
      const row = notes.addRow([header, needed, text]);
      row.alignment = { vertical: 'top', wrapText: true };
      row.getCell(1).font = { bold: true };
      row.eachCell((cell) => { cell.border = border; });
    }
    notes.addRow([]);

    const [packHeading, ...pack] = PACK_NOTES;
    addHeading(packHeading[0]);
    addLines(pack);
    const [rulesHeading, ...rules] = RULE_NOTES;
    addHeading(rulesHeading[0]);
    addLines(rules);
  }

  return workbook.xlsx.writeBuffer();
}

